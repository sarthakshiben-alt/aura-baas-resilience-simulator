/**
 * Exports the SYNTHETIC golden dataset:
 *   data/golden/dataset.json            scenario definitions + expectations
 *   data/golden/telemetry/GS-XX.csv     deterministic per-second telemetry (240 s)
 *   supabase/seed.sql                   golden_scenarios reference rows
 * Re-running produces byte-identical output (deterministic seeds, no Math.random).
 * Usage: npm run golden:export
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { GOLDEN_SCENARIOS } from "../src/lib/golden/dataset";
import { ScriptedRunner } from "../src/lib/golden/harness";
import { ENTITY_IDS } from "../src/lib/sim/types";

const root = path.resolve(__dirname, "..");
const out = path.join(root, "data/golden");
mkdirSync(path.join(out, "telemetry"), { recursive: true });

writeFileSync(
  path.join(out, "dataset.json"),
  JSON.stringify({ synthetic: true, notice: "SYNTHETIC golden dataset for the Aura BaaS resilience simulator. Not real data.", scenarios: GOLDEN_SCENARIOS }, null, 2) + "\n",
);

const header = [
  "t_sim_s", "partner_id", "request_rate_rps", "p50_latency_ms", "p95_latency_ms", "p99_latency_ms", "error_rate",
  "in_flight_requests", "concurrency_limit", "resource_utilisation", "circuit_breaker_state", "health_status",
  "retail_p95_latency_ms", "retail_health",
];
for (const gs of GOLDEN_SCENARIOS) {
  const r = new ScriptedRunner(gs);
  r.advance(240);
  const s = r.state;
  const rows = [header.join(",")];
  for (const g of s.history.gateway) {
    for (const id of ENTITY_IDS) {
      const e = s.history.entities[id][g.t];
      rows.push([g.t, id, e.offeredRps, e.p50Ms ?? "", e.p95Ms ?? "", e.p99Ms ?? "", e.errorRate, e.inFlight, e.concurrencyLimit ?? "", g.utilisation, e.breaker, e.status, g.retailP95Ms ?? "", g.retailHealth].join(","));
    }
  }
  writeFileSync(path.join(out, "telemetry", `${gs.id}.csv`), rows.join("\n") + "\n");
}

const esc = (v: string) => `'${v.replace(/'/g, "''")}'`;
const seed = [
  "-- Generated by scripts/export-golden.ts — SYNTHETIC reference data. Do not edit by hand.",
  "insert into public.golden_scenarios (id, title, description, definition) values",
  GOLDEN_SCENARIOS.map((g) => `  (${esc(g.id)}, ${esc(g.title)}, ${esc(g.description)}, ${esc(JSON.stringify(g))}::jsonb)`).join(",\n"),
  "on conflict (id) do update set title = excluded.title, description = excluded.description, definition = excluded.definition, updated_at = now();",
  "",
].join("\n");
writeFileSync(path.join(root, "supabase/seed.sql"), seed);
console.log(`Exported ${GOLDEN_SCENARIOS.length} golden scenarios.`);
