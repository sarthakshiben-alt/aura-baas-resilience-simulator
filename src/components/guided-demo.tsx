"use client";

import { useRouter } from "next/navigation";
import { CircleCheck, CircleDashed, LoaderCircle, Sparkles, X } from "lucide-react";
import { useSim } from "@/client/provider";
import { latest } from "@/lib/sim/engine";
import { Button } from "@/components/ui/primitives";
import { HealthBadge, RetailBadge, SourceBadge } from "@/components/status";
import { PARTNER_IDS } from "@/lib/sim/types";
import { cn, fmtSecs } from "@/lib/utils";
import { aiValue } from "@/components/ai-value";
import { aiArmStatus } from "@/lib/comparison/metrics";
import { CASE_COST_PER_DOWNTIME_MINUTE_USD } from "@/lib/comparison/business";

const usd = (v: number) => `$${Math.round(Math.max(0, v)).toLocaleString("en-US")}`;
const mins = (sec: number) => `${(Math.round((sec / 60) * 10) / 10).toLocaleString("en-US")} min`;

const TOTAL = 11;

function Check({ done, children }: { done: boolean; children: React.ReactNode }) {
  return (
    <li className="flex items-start gap-1.5">
      {done ? <CircleCheck aria-hidden className="mt-0.5 h-3.5 w-3.5 shrink-0 text-good-text" /> : <CircleDashed aria-hidden className="mt-0.5 h-3.5 w-3.5 shrink-0 text-muted" />}
      <span className={done ? "text-text" : "text-muted"}>{children}</span>
    </li>
  );
}

/** Scripted walkthrough: a routine incident (rules are enough) then a mystery (where AI pays). ~5–7 minutes. */
export function GuidedDemo() {
  const sim = useSim();
  const router = useRouter();
  const step = sim.guideStep;
  if (step === null) return null;
  const s = sim.state;
  const inc = s.incidents[0] ?? null;
  const a = latest(s, "partner-a");
  const retail = s.history.gateway.at(-1)?.retailHealth ?? "healthy";
  const breakerOpened = s.timeline.some((e) => e.kind === "breaker_opened" && e.entityId === "partner-a");
  const diag = inc?.investigations.at(-1) ?? null;
  const pending = inc ? sim.pendingInvestigations.has(inc.id) : false;
  const approved = inc?.recommendations.some((r) => r.approval === "approved") ?? false;
  const go = (n: number | null) => sim.setGuideStep(n);

  let title = "";
  let body: React.ReactNode = null;
  let actions: React.ReactNode = null;

  switch (step) {
    case 0:
      title = "Aura BaaS resilience — guided demo";
      body = (
        <>
          <p>Aura exposes banking capabilities to five fintech partners through one shared gateway, which also serves Aura&apos;s retail customers. This demo answers one question: <b>when is AI worth paying for?</b></p>
          <ol className="list-decimal space-y-1 pl-5 text-xs">
            <li>
              🐢 <b>A routine incident</b> — a partner slows down. Automatic protections contain it and the rulebook knows the fix. AI adds nothing.
            </li>
            <li>
              🎲 <b>A mystery incident</b> — weak, mixed signals that no rule fits. The rulebook has to page a human; AI cracks it in seconds.
            </li>
            <li>
              💰 <b>Value for money</b> — both, side by side, in SLA dollars.
            </li>
          </ol>
          <p className="font-medium text-warning-text">Everything here is simulated. No real banking system is connected.</p>
        </>
      );
      actions = (
        <Button
          variant="primary"
          onClick={async () => {
            await sim.reset();
            sim.setSpeed(5);
            if (!sim.running) sim.start();
            router.push("/");
            go(1);
          }}
        >
          Begin (resets the scenario)
        </Button>
      );
      break;
    case 1:
      title = "Part 1 🐢 · Routine incident — baseline";
      body = (
        <>
          <p>All five partners and retail banking are healthy. Look at the partner table: P95 ≈ 180 ms, ≈ 10 requests in flight against a limit of 100, gateway utilisation ≈ 45%.</p>
          <p>The simulator runs at 5× (one simulated second every 200 ms). Telemetry is generated by a deterministic model, not animated numbers.</p>
        </>
      );
      actions = <Button variant="primary" onClick={() => go(2)}>Next: trigger an incident</Button>;
      break;
    case 2:
      title = "Part 1 🐢 · Trigger a partner slowdown";
      body = (
        <>
          <p>We will slow Partner A&apos;s (Wealth Management) simulated downstream ≈45×. Request volume stays the same, so requests simply stay in flight longer.</p>
          <ul className="space-y-1 text-xs">
            <Check done={!!s.scenarioRuns.length}>Scenario A triggered</Check>
            <Check done={!!a && (a.p95Ms ?? 0) > 400}>Partner A P95 above 400 ms {a?.p95Ms ? `(now ${Math.round(a.p95Ms)} ms)` : ""}</Check>
            <Check done={!!inc}>Monitoring detects the degradation {inc ? `(${inc.detectedAt - inc.startedAt}s after trigger)` : ""}</Check>
          </ul>
        </>
      );
      actions = !s.scenarioRuns.length ? (
        <Button variant="primary" onClick={() => sim.startScenario("partner_slowdown", "partner-a")} data-testid="guide-trigger">
          Trigger Partner A slowdown
        </Button>
      ) : (
        <Button variant="primary" disabled={!inc} onClick={() => go(3)}>
          Next: watch the protections
        </Button>
      );
      break;
    case 3:
      title = "Part 1 🐢 · Automatic protections";
      body = (
        <>
          <p>No AI is involved here. The gateway&apos;s per-partner concurrency limit, 2 s timeout and circuit breaker act on their own rules.</p>
          <ul className="space-y-1 text-xs">
            <Check done={breakerOpened}>Partner A circuit breaker opens (slow/failed calls ≥ 50% over 10 s)</Check>
            <Check done={PARTNER_IDS.filter((p) => p !== "partner-a").every((p) => latest(s, p)?.status === "healthy")}>Partners B–E remain healthy</Check>
            <Check done={retail === "healthy"}>Retail banking within its 300 ms target</Check>
          </ul>
          <div className="flex flex-wrap items-center gap-1.5 text-xs">
            Partner A: {a ? <HealthBadge status={a.status} /> : "—"} Retail: <RetailBadge health={retail} />
          </div>
          <p className="text-xs text-muted">&quot;Protected&quot; means the partner is still impaired for its own customers, but Aura&apos;s shared infrastructure is shielded. An open breaker is protection, not recovery.</p>
        </>
      );
      actions = (
        <Button
          variant="primary"
          disabled={!breakerOpened}
          onClick={() => {
            router.push("/investigation");
            go(4);
          }}
        >
          Next: investigate
        </Button>
      );
      break;
    case 4: {
      title = "Part 1 🐢 · Investigate";
      const triage = sim.manualTriageMinutes;
      body = (
        <>
          {sim.aiMode === "ai_on" ? (
            <p>
              AI assistance is <b>ON</b>. When monitoring detected the incident, an investigation started automatically.{" "}
              {sim.aiRouting ? (
                <>
                  With <b>smart routing</b>, the free rulebook goes first and the AI is only called if the rulebook is stuck. A textbook slowdown like this one? The rulebook knows it — <b>0 AI tokens spent</b>.
                </>
              ) : sim.aiStatus?.configured ? (
                `The configured LLM (${sim.aiStatus.model}) receives a compact summary of the simulated telemetry.`
              ) : (
                "Live AI is not configured here, so the rule-based fallback answers — and is labelled as such."
              )}
            </p>
          ) : triage > 0 ? (
            <p>
              AI assistance is <b>OFF</b>. Conventional response: the on-call engineer was paged at detection. We <b>assume</b> they need <b>{triage} min</b> (simulated) to open dashboards and work the runbook before a diagnosis. That number is an input assumption, not data — the comparison page tests how much it drives the result.
            </p>
          ) : (
            <p>AI assistance is <b>OFF</b> with triage set to 0: the rule-based runbook runs automatically (no AI, no human triage).</p>
          )}
          <p className="text-xs text-muted">Either way, the circuit breaker and concurrency limits are already protecting the platform — investigation only decides the remediation. The simulation keeps running while it&apos;s in flight.</p>
          {diag ? (
            <div className="flex items-center gap-2 text-xs">
              Diagnosis returned: <SourceBadge source={diag.source} status={diag.status} routing={diag.aiRouting} />
            </div>
          ) : pending ? (
            <div className="flex items-center gap-2 text-xs text-muted">
              <LoaderCircle className="h-3.5 w-3.5 animate-spin" /> {sim.aiMode === "ai_off" && triage > 0 ? "Manual triage in progress…" : "Investigating…"}
            </div>
          ) : null}
        </>
      );
      actions = diag ? (
        <Button variant="primary" onClick={() => go(5)}>
          Next: review the recommendation
        </Button>
      ) : pending ? (
        sim.aiMode === "ai_off" && triage > 0 ? (
          <Button variant="secondary" onClick={() => sim.setSpeed(20)}>
            Fast-forward (20×)
          </Button>
        ) : null
      ) : (
        <Button variant="primary" disabled={!inc} onClick={() => inc && void sim.investigate(inc.id)} data-testid="guide-investigate">
          Run investigation
        </Button>
      );
      break;
    }
    case 5: {
      title = "Part 1 🐢 · Human approval";
      const esc = inc?.recommendations.find((r) => r.actionId === "escalate_to_partner" && r.approval === "pending");
      body = (
        <>
          <p>Review the proposed actions in the <b>Action approval</b> panel. Every action is a predefined simulated operation, independently validated by the policy engine. Nothing runs without your approval.</p>
          <p className="text-xs text-muted">Escalating to the partner models remediation 60 s after notification (a disclosed scenario assumption).</p>
          {approved ? <p className="text-xs font-medium text-good-text">Action approved — it will execute in the simulator.</p> : null}
        </>
      );
      actions = approved ? (
        <Button variant="primary" onClick={() => go(6)}>
          Next: verify recovery
        </Button>
      ) : (
        <Button variant="secondary" disabled={!esc || sim.busyRecs.has(esc.id)} onClick={() => esc && inc && void sim.decide(inc.id, esc.id, "approve")}>
          {esc ? "Approve the escalation for me" : "Approve an action in the panel"}
        </Button>
      );
      break;
    }
    case 6: {
      title = "Part 1 🐢 · Verify recovery";
      const remed = s.timeline.some((e) => e.kind === "partner_remediation_completed");
      body = (
        <>
          <ul className="space-y-1 text-xs">
            <Check done={s.timeline.some((e) => e.kind === "partner_remediation_started")}>Partner engineering acknowledged (simulated)</Check>
            <Check done={remed}>Downstream remediation completed; latency ramps back</Check>
            <Check done={inc?.partnerRecoveredAt !== null && inc?.partnerRecoveredAt !== undefined}>Partner A back within thresholds (breaker probe succeeded)</Check>
            <Check done={!!inc?.recoveryVerified}>Recovery verified after 30 s sustained healthy telemetry</Check>
          </ul>
          {inc?.recoveryVerified ? (
            <p className="text-xs">
              Detected in {fmtSecs(inc.detectedAt - inc.startedAt)}, diagnosed at {fmtSecs(inc.diagnosedAt !== null ? inc.diagnosedAt - inc.startedAt : null)}, verified recovery at {fmtSecs(inc.recoveredAt! - inc.startedAt)} (simulated). Retail breach: {inc.retailBreachSeconds} s.
            </p>
          ) : (
            <p className="text-xs text-muted">Partner recovery, gateway protection and incident resolution are tracked separately.</p>
          )}
        </>
      );
      actions = inc?.recoveryVerified ? (
        <Button
          variant="primary"
          onClick={() => {
            sim.setSlaTab("GS-01");
            router.push("/comparison");
            go(7);
          }}
        >
          Next: what did AI add here?
        </Button>
      ) : (
        <Button variant="secondary" onClick={() => sim.setSpeed(20)}>
          Fast-forward (20×)
        </Button>
      );
      break;
    }
    case 7: {
      title = "Part 1 🐢 · What did AI add?";
      const live = sim.pairedByGolden["GS-01"] ?? null;
      const v = aiValue(live, "GS-01", CASE_COST_PER_DOWNTIME_MINUTE_USD);
      body = (
        <>
          <p>The same incident is replayed three ways: a <b>human with a runbook</b> (assumed {sim.manualTriageMinutes} min triage), <b>automated rules</b> (no AI) and <b>rules + AI</b>. Look at the SLA penalty card.</p>
          {live ? (
            <ul className="space-y-1 text-xs">
              <li>
                📘 Automation vs a human: <b className="text-good-text">{usd(v.automationUsd)}</b> saved
              </li>
              <li>
                🤖 AI on top of the rules: <b>{usd(v.aiExtraUsd)}</b>{" "}
                {aiArmStatus(live.on.metrics) === "skipped" ? "— and with smart routing the AI wasn't even called (0 tokens)" : aiArmStatus(live.on.metrics) !== "llm" ? "(AI unavailable in this run — fell back to rules)" : ""}
              </li>
            </ul>
          ) : sim.paired.loading ? (
            <p className="flex items-center gap-2 text-xs text-muted">
              <LoaderCircle className="h-3.5 w-3.5 animate-spin" /> Running all three…
            </p>
          ) : null}
          <p className="text-xs">
            <b>Lesson 1:</b> when the rulebook already knows the failure, AI can&apos;t beat it — the money comes from <b>automating</b> the response. Paying for AI here is pure cost.
          </p>
        </>
      );
      actions = (
        <Button
          variant="primary"
          disabled={!live}
          onClick={() => {
            sim.setSlaTab("GS-19");
            go(8);
          }}
        >
          Next: a mystery incident 🎲
        </Button>
      );
      break;
    }
    case 8: {
      title = "Part 2 🎲 · The mystery incident";
      const live = sim.pairedByGolden["GS-19"] ?? null;
      const llm = !!live && aiArmStatus(live.on.metrics) === "llm";
      body = (
        <>
          <p>
            One partner is quietly failing — a bit slower, a few more errors, a bit more traffic — and <b>every signal sits just under a rulebook threshold</b>. Red herrings elsewhere look suspicious but are harmless. It&apos;s randomised every roll.
          </p>
          {live ? (
            <ul className="space-y-1 text-xs">
              <Check done>📘 Rulebook: &quot;can&apos;t tell what&apos;s wrong&quot; → pages a human, who needs the assumed {sim.manualTriageMinutes} min → {mins(live.rules.metrics.primarySlaBreachSeconds)} outside SLA</Check>
              <Check done={llm}>
                🤖 AI: {llm ? <>{live.on.humanDiagnosedAt === null ? "named the right partner and escalated straight away" : "didn't crack it, a human had to"} → {mins(live.on.metrics.primarySlaBreachSeconds)} outside SLA</> : "unavailable in this run (free AI quota) — the next step uses your recorded live run instead"}
              </Check>
            </ul>
          ) : sim.paired.loading ? (
            <p className="flex items-center gap-2 text-xs text-muted">
              <LoaderCircle className="h-3.5 w-3.5 animate-spin" /> Running the mystery three ways…
            </p>
          ) : (
            <p className="text-xs text-muted">Starting the comparison… (the free AI tier may ask for a short cool-down)</p>
          )}
          <p className="text-xs text-muted">Here the rulebook is stuck, so smart routing <b>does</b> call the AI. Open &quot;Reveal what really happened&quot; on the card to see the rolled cause and the red herrings.</p>
        </>
      );
      actions = (
        <Button
          variant="primary"
          disabled={!live && !sim.paired.error}
          onClick={() => {
            document.querySelector('[data-testid="where-ai-pays"]')?.scrollIntoView({ behavior: "smooth", block: "start" });
            go(9);
          }}
        >
          Next: value for money 💰
        </Button>
      );
      break;
    }
    case 9: {
      title = "Part 3 💰 · Value for money";
      const r = aiValue(sim.pairedByGolden["GS-01"] ?? null, "GS-01", CASE_COST_PER_DOWNTIME_MINUTE_USD);
      const m = aiValue(sim.pairedByGolden["GS-19"] ?? null, "GS-19", CASE_COST_PER_DOWNTIME_MINUTE_USD);
      body = (
        <>
          <p>Extra SLA penalty avoided by adding AI to the rulebook (at the assumed $4,500/min):</p>
          <table className="tabular w-full text-xs" data-testid="guide-value">
            <tbody>
              <tr className="border-b border-border">
                <td className="py-1">🐢 Routine incident</td>
                <td className="py-1 text-right font-bold">{usd(r.aiExtraUsd)}</td>
                <td className="py-1 pl-2 text-right text-muted">{r.source === "live" ? "live" : `recorded ${r.date}`}</td>
              </tr>
              <tr>
                <td className="py-1">🎲 Mystery incident</td>
                <td className="py-1 text-right font-bold text-good-text">{usd(m.aiExtraUsd)}</td>
                <td className="py-1 pl-2 text-right text-muted">{m.source === "live" ? "live" : `recorded ${m.date}`}</td>
              </tr>
            </tbody>
          </table>
          <p className="text-xs">
            {m.breakEvenPer1kTokensUsd !== null && m.tokens ? (
              <>
                The mystery cost {m.tokens.toLocaleString("en-US")} AI tokens. AI would have to cost over <b>{usd(m.breakEvenPer1kTokensUsd)} per 1,000 tokens</b> to stop paying for itself — and this demo runs on a free tier.
              </>
            ) : (
              <>One or two AI calls — a few thousand tokens — bought back about {mins(m.rulesS - m.aiS)} of SLA breach. This demo runs on a free AI tier.</>
            )}
          </p>
          <p className="text-xs">
            <b>Lesson 2:</b> don&apos;t put AI on everything. Let the rulebook handle what it knows, and send AI the incidents it <b>can&apos;t</b> classify — that&apos;s where it pays.
          </p>
        </>
      );
      actions = (
        <Button variant="primary" onClick={() => go(10)}>
          Finish
        </Button>
      );
      break;
    }
    default:
      title = "That's the story";
      body = (
        <>
          <ol className="list-decimal space-y-1 pl-5 text-xs">
            <li>
              🛡️ <b>Protections first.</b> The gateway&apos;s automatic controls kept retail and the other partners safe in every case — no AI involved.
            </li>
            <li>
              📘 <b>Automate what you know.</b> Rules that run on detection beat waiting for a human. That&apos;s most of the money on routine incidents.
            </li>
            <li>
              🤖 <b>AI for the unknown.</b> Where no rule fits, AI turns a paged-human wait into a seconds-long diagnosis. A human still approves every action, and the policy engine blocks unsafe ones.
            </li>
          </ol>
          <p className="text-xs text-muted">Caveats live on the page: the $/min and the human&apos;s triage time are assumptions, and the AI sometimes picks the right fix with the wrong label — which is exactly why a human approves.</p>
        </>
      );
      actions = (
        <>
          <Button variant="primary" onClick={() => go(0)}>
            Restart demo
          </Button>
          <Button variant="ghost" onClick={() => go(null)}>
            Free exploration
          </Button>
        </>
      );
  }

  return (
    <aside aria-label="Guided demo" className="fixed bottom-4 right-4 z-40 max-h-[80vh] w-[min(420px,calc(100vw-2rem))] overflow-y-auto rounded-2xl border border-accent/40 bg-surface shadow-2xl" data-testid="guided-demo">
      <div className="flex items-center justify-between border-b border-border px-3 py-2">
        <div className="flex items-center gap-1.5 text-xs font-semibold text-info-text">
          <Sparkles className="h-3.5 w-3.5" /> Guided demo · step {Math.min(step + 1, TOTAL)} of {TOTAL}
        </div>
        <button onClick={() => go(null)} className="rounded p-1 text-muted hover:bg-surface-2" aria-label="Close guided demo">
          <X className="h-4 w-4" />
        </button>
      </div>
      <div className="h-1 bg-surface-2">
        <div className={cn("h-1 bg-accent transition-all")} style={{ width: `${((step + 1) / TOTAL) * 100}%` }} />
      </div>
      <div className="space-y-2 px-3 py-3 text-sm text-text-2">
        <h3 className="text-sm font-semibold text-text">{title}</h3>
        {body}
      </div>
      <div className="flex flex-wrap gap-2 border-t border-border px-3 py-2">{actions}</div>
    </aside>
  );
}
